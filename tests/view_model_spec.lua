local UiHarness = dofile("tests/support/ui_harness.lua")

describe("ViewModel", function()
  local h, VM

  before_each(function()
    h = UiHarness.Build()
    VM = h.ns.ViewModel
    h.ns.Locale.Use("enUS")
  end)

  it("formats a timestamp as dd/mm/yy and tolerates junk", function()
    local stamp = os.time({ year = 2026, month = 11, day = 5, hour = 12 })
    assert.are.equal("05/11/26", VM.FormatDate(stamp))
    assert.are.equal("", VM.FormatDate(nil))
    assert.are.equal("", VM.FormatDate("x"))
    assert.are.equal("", VM.FormatDate(-1))
    VM.dateFn = function()
      error("no clock")
    end
    assert.are.equal("", VM.FormatDate(5))
  end)

  it("labels retro grants as earned before the addon", function()
    local stamp = os.time({ year = 2026, month = 11, day = 5, hour = 12 })
    assert.are.equal("Earned before the addon", VM.DateLabel({ at = stamp, retro = true }))
    assert.are.equal("05/11/26", VM.DateLabel({ at = stamp, retro = false }))
    assert.are.equal("", VM.DateLabel(nil))
    assert.are.equal("Earned by Hero on 05/11/26", VM.EarnedByLabel("Hero", { at = stamp }))
    assert.are.equal("Earned by Hero before the addon", VM.EarnedByLabel("Hero", { retro = true }))
    assert.is_truthy(VM.EarnedByLabel(nil, { at = stamp }):find("Unknown character", 1, true))
  end)

  it("hides the points of feats and empty values", function()
    assert.are.equal("10", VM.PointsText(10, false))
    assert.are.equal("", VM.PointsText(10, true))
    assert.are.equal("", VM.PointsText(0, false))
    assert.are.equal("", VM.PointsText(nil, false))
  end)

  it("never divides by zero", function()
    assert.are.equal(0, VM.Fraction(0, 0))
    assert.are.equal(0, VM.Fraction(3, 0))
    assert.are.equal(0, VM.Fraction(-1, 5))
    assert.are.equal(0, VM.Fraction(nil, 5))
    assert.are.equal(1, VM.Fraction(9, 5))
    assert.are.equal(0.5, VM.Fraction(1, 2))
    assert.are.equal("3/10", VM.FractionText(3, 10))
    assert.are.equal("0/0", VM.FractionText())
  end)

  it("formats numbers, money and durations", function()
    assert.are.equal("1,234,567", VM.Thousands(1234567))
    assert.are.equal("999", VM.Thousands(999))
    assert.are.equal("-1,000", VM.Thousands(-1000))
    assert.are.equal("0", VM.Thousands(nil))
    assert.are.equal("12g 5s 3c", VM.Money(120503))
    assert.are.equal("1,000g", VM.Money(10000000))
    assert.are.equal("0c", VM.Money(0))
    assert.are.equal("5s", VM.Money(500))
    assert.are.equal("3d 4h", VM.Duration(3 * 86400 + 4 * 3600 + 59))
    assert.are.equal("2h 5m", VM.Duration(2 * 3600 + 300))
    assert.are.equal("0m", VM.Duration(-5))
    assert.are.equal("45m", VM.Duration(2700))
    assert.are.equal("1g", VM.FormatValue("money", 10000))
    assert.are.equal("1h 0m", VM.FormatValue("played", 3600))
    assert.are.equal("60", VM.FormatValue("level", 60))
  end)

  it("folds case and accents for the search", function()
    assert.are.equal("exploracion", VM.Fold("Exploración"))
    assert.are.equal("nino anos", VM.Fold("NIÑO AÑOS"))
    assert.are.equal("aeiou", VM.Fold("ÁÉÍÓÚ"))
    assert.are.equal("", VM.Fold(nil))
    assert.are.equal("cafe", VM.Fold("Café"))
  end)

  it("reads a locale text or a fallback", function()
    assert.are.equal("Close", VM.TextOr("ui.close", "x"))
    assert.are.equal("fallback", VM.TextOr("no.such.key", "fallback"))
    h.ns.Locale.Use("esES")
    assert.are.equal("Cerrar", VM.TextOr("ui.close", "x"))
    h.ns.Locale.Register("enUS", { ["only.en"] = "English only" })
    assert.are.equal("English only", VM.TextOr("only.en", "x"))
  end)

  it("finds names, descriptions and icons", function()
    assert.are.equal("Test t_level", VM.Name(h.ns.Catalog, "t_level"))
    assert.are.equal("Test description of t_level", VM.Desc(h.ns.Catalog, "t_level"))
    assert.are.equal(134400, VM.Icon(h.ns.Catalog.Get("t_level")))
    assert.are.equal(VM.FALLBACK_ICON, VM.Icon(nil))
    assert.are.equal(VM.FALLBACK_ICON, VM.Icon({}))
  end)

  it("reads the guid from a string or a function", function()
    assert.are.equal("Player-1", VM.Guid({ guid = "Player-1" }))
    assert.are.equal(
      "Player-1",
      VM.Guid({
        guid = function()
          return "Player-1"
        end,
      })
    )
    assert.is_nil(VM.Guid({ guid = "" }))
    assert.is_nil(VM.Guid({}))
    assert.is_nil(VM.Guid(nil))
  end)
end)
